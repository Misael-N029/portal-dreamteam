export const ICON_NAMES = Object.keys(MODULE_ICONS);

export function ModuleIcon({ name, className }: { name: string; className?: string }) {
  const Icon = MODULE_ICONS[name] ?? LayoutGrid;
  return <Icon className={className} />;
}

/** Color del icono de un módulo. Los casi negros usan el color del texto para verse también en modo oscuro. */
export function moduleTint(color: string): string | undefined {
  const n = parseInt(color.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b < 70 ? undefined : color;
}
